import { z } from "zod";

export const studentFormSchema = z
  .object({
    subject: z.enum(["math", "portuguese"]),
    prediction_mode: z.enum(["early", "mid_year"]),

    // Demographics
    school: z.enum(["GP", "MS"]),
    sex: z.enum(["F", "M"]),
    age: z.number().min(15).max(22),
    address: z.enum(["U", "R"]),
    famsize: z.enum(["LE3", "GT3"]),
    Pstatus: z.enum(["T", "A"]),

    // Family
    Medu: z.number().min(0).max(4),
    Fedu: z.number().min(0).max(4),
    Mjob: z.enum(["teacher", "health", "services", "at_home", "other"]),
    Fjob: z.enum(["teacher", "health", "services", "at_home", "other"]),
    reason: z.enum(["home", "reputation", "course", "other"]),
    guardian: z.enum(["mother", "father", "other"]),

    // Study & Support
    traveltime: z.number().min(1).max(4),
    studytime: z.number().min(1).max(4),
    failures: z.number().min(0).max(4),
    schoolsup: z.enum(["yes", "no"]),
    famsup: z.enum(["yes", "no"]),
    paid: z.enum(["yes", "no"]),
    activities: z.enum(["yes", "no"]),
    nursery: z.enum(["yes", "no"]),
    higher: z.enum(["yes", "no"]),
    internet: z.enum(["yes", "no"]),
    romantic: z.enum(["yes", "no"]),

    // Lifestyle & Attendance
    famrel: z.number().min(1).max(5),
    freetime: z.number().min(1).max(5),
    goout: z.number().min(1).max(5),
    Dalc: z.number().min(1).max(5),
    Walc: z.number().min(1).max(5),
    health: z.number().min(1).max(5),
    absences: z.number().min(0).max(93),

    // Term Grades (optional for early, validated if mid_year)
    G1: z.number().min(0).max(20).optional(),
    G2: z.number().min(0).max(20).optional(),
  })
  .refine(
    (data) => {
      if (data.prediction_mode === "mid_year") {
        return data.G1 !== undefined && data.G2 !== undefined;
      }
      return true;
    },
    {
      message: "First and Second period grades (G1, G2) are required for Mid-Year Estimate mode.",
      path: ["G1"],
    }
  );

export type StudentFormData = z.infer<typeof studentFormSchema>;

